#!/usr/bin/env node
// Regenerates src/printers/bambu-models.ts from Bambu Studio's printer profiles.
// Usage: node scripts/sync-bambu-models.mjs [git-ref]   (default: the latest commit on master)
import { writeFile } from "node:fs/promises"

const repo = "bambulab/BambuStudio"
const api = (path) =>
  fetch(`https://api.github.com/repos/${repo}/${path}`, { headers: { accept: "application/vnd.github+json" } }).then((r) => {
    if (!r.ok) throw new Error(`GET ${path}: ${r.status}`)
    return r.json()
  })

const ref = process.argv[2] ?? (await api("commits/master")).sha
const listing = await api(`contents/resources/printers?ref=${ref}`)
const profiles = listing.filter((f) => f.name.endsWith(".json") && !f.name.includes("blacklist"))

const firstValue = (node, key) => {
  if (!node || typeof node !== "object") return undefined
  if (typeof node[key] === "string") return node[key]
  for (const child of Object.values(node)) {
    const found = firstValue(child, key)
    if (found !== undefined) return found
  }
  return undefined
}

const rows = []
for (const file of profiles) {
  const profile = await fetch(file.download_url).then((r) => r.json())
  const code = firstValue(profile, "model_id")
  const name = firstValue(profile, "display_name")?.replace(/^Bambu Lab /, "")
  const snPrefix = firstValue(profile, "sn_prefix")
  if (!code || !name || name === code) continue
  rows.push({ code, name, snPrefix })
}
rows.sort((a, b) => a.code.localeCompare(b.code))

const body = `// Generated by scripts/sync-bambu-models.mjs from ${repo}@${ref.slice(0, 7)}. Do not edit.

export interface BambuModel {
  readonly name: string
  readonly snPrefix?: string
}

/** Keyed by \`DevModel.bambu.com\` code, which Bambu Studio calls \`model_id\`. */
export const bambuModels: Readonly<Record<string, BambuModel>> = {
${rows.map((r) => `  ${JSON.stringify(r.code)}: { name: ${JSON.stringify(r.name)}${r.snPrefix ? `, snPrefix: ${JSON.stringify(r.snPrefix)}` : ""} },`).join("\n")}
}
`
await writeFile(new URL("../src/printers/bambu-models.ts", import.meta.url), body)
console.log(`wrote ${rows.length} models from ${repo}@${ref.slice(0, 7)}`)
